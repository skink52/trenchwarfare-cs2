"""Mortar sounds (synthesised) + sound events for mg_trenchwarfare, merged into the addon's soundevents_addon.vsndevts."""
import os, sys, wave
import numpy as np

OUT = sys.argv[1]; TEMPLATE = sys.argv[2]
SR = 44100
rng = np.random.RandomState(4)
d = os.path.join(OUT, 'sounds/tw'); os.makedirs(d, exist_ok=True)

def write(name, x):
    x = x / (np.max(np.abs(x)) + 1e-9) * 0.92
    with wave.open(os.path.join(d, name + '.wav'), 'wb') as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes((x * 32000).astype(np.int16).tobytes())

def lp(x, a):
    y = np.zeros_like(x); acc = 0.0
    for i in range(len(x)): acc += a * (x[i] - acc); y[i] = acc
    return y

def env(n, att, dec):
    t = np.arange(n) / SR
    return np.minimum(t / att, 1) * np.exp(-t / dec)

# launch: deep thump + tube ring + a puff of hiss
n = int(SR * 1.6); t = np.arange(n) / SR
f = 55 * np.exp(-t * 3) + 32
boom = np.sin(2 * np.pi * np.cumsum(f) / SR) * env(n, 0.003, 0.22)
ring = (np.sin(2 * np.pi * 410 * t) * 0.35 + np.sin(2 * np.pi * 980 * t) * 0.15) * env(n, 0.001, 0.12)
hiss = lp(rng.normal(0, 1, n), 0.25) * env(n, 0.002, 0.08) * 0.6
crack = lp(rng.normal(0, 1, n), 0.6) * env(n, 0.0005, 0.015)
write('mortar_launch', boom * 1.2 + ring + hiss + crack)

# incoming: falling whistle with a little flutter, swelling as it arrives
n = int(SR * 2.1); t = np.arange(n) / SR
fw = 1500 - 900 * (t / t[-1]) ** 1.4
ph = 2 * np.pi * np.cumsum(fw + 18 * np.sin(2 * np.pi * 7 * t)) / SR
amp = (0.15 + 0.85 * (t / t[-1]) ** 2.2) * np.minimum(1, (t[-1] - t) / 0.03)
air = lp(rng.normal(0, 1, n), 0.08) * 0.25
write('mortar_whistle', (np.sin(ph) * 0.8 + np.sin(ph * 2.01) * 0.15) * amp + air * amp)

ev = ['\t// ---- mg_trenchwarfare (generated by tools/sounds.py) ----']
def curve(points):
    out = ['\t\t[']
    for dist, v in points:
        out += ['\t\t\t[', '\t\t\t\t%.1f, %.2f, 0.0, 0.0,' % (dist, v), '\t\t\t\t2.0, 3.0,', '\t\t\t],']
    return out + ['\t\t]']
def event(name, files, vol, rng_, extra=()):
    fl = files if isinstance(files, str) else None
    out = ['\t"%s" =' % name, '\t{', '\t\ttype = "csgo_mega"', '\t\tvolume = %.2f' % vol, '\t\tpitch = 1.0']
    if fl: out.append('\t\tvsnd_files_track_01 = "%s"' % fl)
    else: out += ['\t\tvsnd_files_track_01 =', '\t\t['] + ['\t\t\t"%s",' % f for f in files] + ['\t\t]']
    out += list(extra)
    out += ['\t\tdistance_volume_mapping_curve ='] + curve([(0, 1), (rng_ * 0.15, 1), (rng_, 0)]) + ['\t}']
    return out
ev += event('tw.mortar_launch', ['sounds/tw/mortar_launch.vsnd', 'sounds/weapons/c4/c4_thump_01.vsnd'], 1.0, 4500)
ev += event('tw.mortar_whistle', 'sounds/tw/mortar_whistle.vsnd', 0.9, 3000)
ev += event('tw.mortar_impact', ['sounds/weapons/hegrenade/hegrenade_detonate_02.vsnd', 'sounds/weapons/hegrenade/hegrenade_detonate_03.vsnd',
                                 'sounds/weapons/c4/c4_explode1.vsnd'], 1.0, 9000)
# front-line soundscape: wind, distant guns (thunder), crows
ev += ['\t"tw.amb.front" =', '\t{', '\t\tbase = "amb.soundscapeParent.base"', '\t\tenable_child_events = true', '\t\tsoundevent_01 =', '\t\t[',
       '\t\t\t"tw.amb.wind",', '\t\t\t"tw.amb.guns",', '\t\t\t"tw.amb.crows",', '\t\t]', '\t}',
       '\t"tw.amb.wind" =', '\t{', '\t\tbase = "amb.looping.stereo.base"', '\t\tvolume = 0.55', '\t\tvsnd_files_track_01 = "sounds/ambient/anubis/wind_low_amb.vsnd"', '\t}',
       '\t"tw.amb.guns" =', '\t{', '\t\tbase = "amb.intermittent.randomAroundPlayer.base"', '\t\tvolume = 0.9',
       '\t\trandomize_position_min_radius = 2500.0', '\t\trandomize_position_max_radius = 5000.0', '\t\tretrigger_interval_min = 3.0', '\t\tretrigger_interval_max = 11.0',
       '\t\tvsnd_files_track_01 =', '\t\t['] + ['\t\t\t"sounds/ambient/common/thunder/thunder_distant_%02d.vsnd",' % i for i in range(1, 9)] + ['\t\t]', '\t}',
       '\t"tw.amb.crows" =', '\t{', '\t\tbase = "amb.intermittent.randomAroundPlayer.base"', '\t\tvolume = 0.5',
       '\t\trandomize_position_min_radius = 800.0', '\t\trandomize_position_max_radius = 2000.0', '\t\tretrigger_interval_min = 14.0', '\t\tretrigger_interval_max = 40.0',
       '\t\tvsnd_files_track_01 =', '\t\t['] + ['\t\t\t"sounds/ambient/common/animal/crows_%02d.vsnd",' % i for i in range(1, 11)] + ['\t\t]', '\t}']
ev.append('\t// ---- end mg_trenchwarfare ----')
body = '\n'.join(ev) + '\n'
tpl = open(TEMPLATE, encoding='utf-8').read()
if '// ---- mg_trenchwarfare' in tpl:
    a = tpl.index('\t// ---- mg_trenchwarfare'); b = tpl.index('\t// ---- end mg_trenchwarfare ----\n') + len('\t// ---- end mg_trenchwarfare ----\n')
    tpl = tpl[:a] + tpl[b:]
first = tpl.index('\n{') + 2
os.makedirs(os.path.join(OUT, 'soundevents'), exist_ok=True)
open(os.path.join(OUT, 'soundevents/soundevents_addon.vsndevts'), 'w', newline='\n', encoding='utf-8').write(tpl[:first] + body + tpl[first:])
print('sounds written')
